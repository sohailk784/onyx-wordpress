import { chromium } from 'playwright-core';
const H='http://localhost:8088';
const b=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']});
const ctx=await b.newContext({viewport:{width:1440,height:900}});
await ctx.addCookies([{name:'onyx_age_verified',value:'1',domain:'localhost',path:'/'}]);
const p=await ctx.newPage();
p.on('response',async r=>{if(r.request().method()==='POST'&&!r.url().includes('fragments'))console.log('BODY',r.request().postData()?.replace(/------WebKit[^\r]*\r\n/g,'|').replace(/Content-Disposition: form-data; /g,'').replace(/\r\n/g,' ').slice(0,700),'=>',(await r.text().catch(()=>'')).slice(0,300));if(r.url().includes('wishlist')||r.url().includes('admin-ajax')||r.url().includes('wc-ajax'))console.log('RESP',r.request().method(),r.url().slice(0,120),r.status())});
await p.goto(H+'/peptides/',{waitUntil:'networkidle'});
const hits=p.locator('.onyx-wish-hit a');
console.log(await hits.nth(0).evaluate(e=>e.outerHTML));
console.log(await hits.nth(3).evaluate(e=>e.outerHTML.slice(0,200)));
await hits.nth(0).click({force:true});await p.waitForTimeout(3000);
console.log('after1',await hits.nth(0).getAttribute('class'));
await hits.nth(3).click({force:true});await p.waitForTimeout(3000);
console.log('url',p.url());
await p.goto(H+'/wishlist/',{waitUntil:'networkidle'});console.log('cards',await p.locator('.onyx-wishlist .group').count());
const a=p.locator('.onyx-wishlist .onyx-wish-hit a').first();console.log(await a.getAttribute('class'));
await a.click({force:true});await p.waitForTimeout(3000);
await p.goto(H+'/wishlist/',{waitUntil:'networkidle'});console.log('cards after remove',await p.locator('.onyx-wishlist .group').count());
await b.close();
